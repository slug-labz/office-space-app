/**
 * Local checks refuse what they cannot vouch for: uncommitted changes, a tree or HEAD that
 * changes under the run, a checkout holding worktrees, and a flag npm kept for itself. A temp
 * folder a run cannot remove is named, not ignored.
 *
 * One of six files that pin `scripts/ci-local.mjs`'s promises; the list, and the rig they
 * share, are in `local-checks-rig.ts`. Split from one file on 2026-09-24 so that each fits the
 * suite’s minute per file on a loaded machine.
 */

import { test } from 'node:test'
import assert from 'node:assert/strict'
import { chmod, mkdir, readdir, realpath, rm, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { spawnSync } from 'node:child_process'
import { join } from 'node:path'

import { SKIP, type Rig, gitIn, aRepo, withOrigin, commit, posted, run, start, lines, seen, until, collect, pidsWritten, pidFile, report } from './local-checks-rig.js'

test('uncommitted changes are refused, unless asked for, and never posted', { skip: SKIP }, async (t) => {
  const rig = await aRepo(t)
  // An origin that takes posts, so that the dirty tree is the only thing that can refuse one.
  await withOrigin(rig)
  await writeFile(join(rig.root, 'scripts', 'extra.mjs'), '// not committed\n')

  const refused = run(rig)
  assert.equal(refused.code, 2)
  assert.match(refused.stderr, /uncommitted changes/)
  assert.deepEqual(await seen(rig), [], 'a dirty tree was run without being asked')

  const dirtyPost = run(rig, ['--allow-dirty', '--post-status'])
  assert.equal(dirtyPost.code, 2, `a result for a commit that did not run was about to be posted: ${dirtyPost.stdout}`)
  assert.match(dirtyPost.stderr, /^refused: --post-status on a dirty tree would record a result for a commit that did not run\.$/m)
  assert.deepEqual(await seen(rig), [])
  assert.deepEqual(await lines(rig.ghLog), [], 'gh was asked to post')

  const allowed = run(rig, ['--allow-dirty'])
  assert.equal(allowed.code, 0, allowed.stderr)
  assert.match(allowed.stdout, /\(with uncommitted changes\)/, 'the report does not say the tree was dirty')
  assert.equal((await report(rig))['dirty'], true)

  // Committed, the same checkout is posted: nothing but the dirty tree stood in the way.
  gitIn(rig.root, 'add', '-A')
  const head = commit(rig, 'commit what was dirty')
  const clean = run(rig, ['--post-status'])
  assert.equal(clean.code, 0, clean.stderr)
  const { path, fields } = await posted(rig)
  assert.equal(path, `repos/o/r/statuses/${head}`)
  assert.equal(fields['state'], 'success')
})

test('a change under graphify-out alone does not count as uncommitted', { skip: SKIP }, async (t) => {
  const rig = await aRepo(t)
  await mkdir(join(rig.root, 'graphify-out'))
  await writeFile(join(rig.root, 'graphify-out', 'GRAPH_REPORT.md'), 'regenerated by a hook\n')
  const r = run(rig)
  assert.equal(r.code, 0, r.stderr)
  assert.equal((await report(rig))['dirty'], false)
})

test('a copy kept in another checkout checks the checkout it is run from', { skip: SKIP }, async (t) => {
  const elsewhere = await aRepo(t)
  const branch = await aRepo(t, { script: false })
  const r = run(branch, [], {}, join(elsewhere.root, 'scripts', 'ci-local.mjs'))
  assert.equal(r.code, 0, r.stderr)
  const where = new Set((await seen(branch)).map((line) => line.split(' ')[2]))
  assert.deepEqual([...where], [await realpath(branch.root)], 'the steps ran in the checkout the script sits in, not the one it was run from')
  const head = gitIn(branch.root, 'rev-parse', 'HEAD')
  assert.equal((await report(branch))['sha'], head)
  assert.equal(existsSync(join(branch.root, 'scripts')), false, 'the branch was given a copy of the script')
})

test('a checkout that holds other checkouts is refused before anything is copied', { skip: SKIP }, async (t) => {
  const rig = await aRepo(t)
  await mkdir(join(rig.root, '.claude', 'worktrees', 'someone-else'), { recursive: true })
  const r = run(rig)
  assert.equal(r.code, 2)
  assert.match(r.stderr, /instructions\.test\.ts copies this checkout's whole \.claude\//)
  assert.deepEqual(await seen(rig), [], 'the suite ran in a checkout full of worktrees')
})

test('a run whose HEAD or tree changed under it fails, and posts nothing', { skip: SKIP }, async (t) => {
  const cases = [
    { env: { STEP_COMMIT: 'build' }, says: /^changed {5}HEAD moved during the run, from [0-9a-f]{7} to [0-9a-f]{7}$/m },
    { env: { STEP_EDIT: 'build' }, says: /^changed {5}the tree changed during the run: README \(M\)$/m },
    { env: { STEP_ADD: 'typecheck' }, says: /^changed {5}the tree changed during the run: made-during-the-run\.txt \(\?\?\)$/m },
  ]
  for (const c of cases) {
    const what = Object.keys(c.env).join()
    const rig = await aRepo(t)
    await withOrigin(rig)
    const head = gitIn(rig.root, 'rev-parse', 'HEAD')
    const r = run(rig, ['--post-status'], c.env)
    assert.equal(r.code, 1, `${what}: ${r.stdout}`)
    assert.match(r.stdout, c.says, what)
    assert.match(r.stdout, /^result {6}FAILED$/m, what)
    assert.match(r.stderr, /status not posted: .*describes no single commit/, what)
    assert.deepEqual(await lines(rig.ghLog), [], `${what}: a result for a tree that changed under the run was posted`)
    assert.equal((await report(rig, head))['passed'], false, what)
  }
})

test('a modified tracked file counts as uncommitted, as a new file does', { skip: SKIP }, async (t) => {
  const rig = await aRepo(t)
  await writeFile(join(rig.root, 'README'), 'changed, and not committed\n')
  const r = run(rig)
  assert.equal(r.code, 2, r.stdout)
  assert.match(r.stderr, /uncommitted changes/)
  assert.deepEqual(await seen(rig), [])
})

test('run from a subdirectory, it checks the whole checkout, and still refuses one that holds worktrees', { skip: SKIP }, async (t) => {
  const rig = await aRepo(t)
  const fromBelow = () =>
    spawnSync(process.execPath, [join(rig.root, 'scripts', 'ci-local.mjs')], {
      cwd: join(rig.root, 'scripts'),
      env: { ...process.env, ...rig.env },
      encoding: 'utf8',
      timeout: 30_000,
    })
  const r = fromBelow()
  assert.equal(r.status, 0, r.stderr)
  assert.deepEqual([...new Set((await seen(rig)).map((line) => line.split(' ')[2]))], [rig.root], 'the steps did not run at the top of the checkout')

  await mkdir(join(rig.root, '.claude', 'worktrees', 'someone-else'), { recursive: true })
  const refused = fromBelow()
  assert.equal(refused.status, 2, refused.stdout)
  assert.match(refused.stderr, /holds other checkouts/)
})

test('a flag npm kept for itself is refused, rather than run without', { skip: SKIP }, async (t) => {
  const rig = await aRepo(t)
  await withOrigin(rig)
  // What npm 10 gives a script run as `npm run checks:local --post-status`, without `--`: no
  // arguments, and the flag as a setting of npm's own.
  const npm = { npm_lifecycle_event: 'checks:local', npm_config_post_status: 'true' }
  const lost = run(rig, [], npm)
  assert.equal(lost.code, 2, lost.stdout)
  assert.match(lost.stderr, /^refused: npm kept --post-status for itself, so this run would go ahead without it\. Put the flags after --: npm run checks:local -- --post-status$/m)
  assert.deepEqual(await seen(rig), [], 'the run went ahead without the flag it was given')
  assert.deepEqual(await lines(rig.ghLog), [])

  const both = run(rig, [], { ...npm, npm_config_allow_dirty: 'true' })
  assert.equal(both.code, 2, both.stdout)
  assert.match(both.stderr, /npm kept --post-status and --allow-dirty for itself.*-- --post-status --allow-dirty$/m)

  // `npm run checks:local --allow-dirty -- --post-status`: one flag reached the script, one did not,
  // and the command to run instead keeps both.
  const split = run(rig, ['--post-status'], { npm_lifecycle_event: 'checks:local', npm_config_allow_dirty: 'true' })
  assert.equal(split.code, 2, split.stdout)
  assert.match(split.stderr, /^refused: npm kept --allow-dirty for itself, .* Put the flags after --: npm run checks:local -- --post-status --allow-dirty$/m)

  // `--no-post-status` leaves the setting empty, and asks for what a run does anyway.
  const no = run(rig, [], { ...npm, npm_config_post_status: '' })
  assert.equal(no.code, 0, no.stderr)
  assert.deepEqual(await lines(rig.ghLog), [])

  // After `--`, the flag reaches the script, and is taken.
  const through = run(rig, ['--post-status'], npm)
  assert.equal(through.code, 0, through.stderr)
  assert.equal((await posted(rig)).fields['state'], 'success')
})

test('a temp folder the run cannot remove is named and left, and the run still releases its lock and ends as its checks say', { skip: SKIP }, async (t) => {
  // Whether a directory nobody may read stops this user is asked of the disk, not of the script:
  // root removes one whatever its mode says.
  const scratch = await aRepo(t)
  const probe = join(scratch.base, 'probe')
  await mkdir(join(probe, 'inside'), { recursive: true })
  await chmod(probe, 0o000)
  const removable = await rm(probe, { recursive: true, force: true }).then(
    () => true,
    () => false,
  )
  if (!removable) await chmod(probe, 0o755)
  if (removable) {
    t.skip('this user can remove a directory it may not read (root can, whatever the mode bits say), so a folder the run cannot remove cannot be made')
    return
  }
  /** Lets the fixture's own removal in again. If this test is killed first, the rig stays behind. */
  const unlock = async (rig: Rig) => {
    for (const folder of await readdir(rig.tmpBase)) await chmod(join(rig.tmpBase, folder, 'office-locked'), 0o755).catch(() => {})
  }

  const cases = [
    { what: 'a passing run, posted', env: { STEP_LOCK_DIR: 'build' }, stop: false, code: 0, entries: 2, says: [/^result {6}PASSED$/m, /^status {6}local-checks = success/m] },
    {
      what: 'a step past its ceiling',
      env: { STEP_LOCK_DIR: 'typecheck', STEP_HANG: 'build', OFFICE_CHECKS_CEILING_SECONDS: '1' },
      stop: false,
      code: 1,
      entries: 1,
      says: [/^typecheck {13}passed in/m, /^build {17}timed out in [\d.]+s, at its ceiling of 1s$/m, /^tests, with coverage {2}not run, because an earlier step failed$/m, /^result {6}FAILED$/m],
    },
    {
      what: 'a run stopped by SIGINT',
      env: { STEP_LOCK_DIR: 'typecheck', STEP_HANG: 'build' },
      stop: true,
      code: 130,
      entries: 1,
      says: [/^stopped {5}by SIGINT/m, /^typecheck {13}passed in/m, /^tests, with coverage {2}not run, because the run was stopped$/m, /^result {6}FAILED$/m, /^status not posted: the run was stopped/m],
    },
  ]
  for (const c of cases) {
    const rig = await aRepo(t)
    await withOrigin(rig)
    const pids = pidFile(t)
    try {
      let r: { code: number | null; stdout: string; stderr: string }
      if (c.stop) {
        const running = start(t, rig, ['--post-status'], { ...c.env, PIDS: pids })
        await pidsWritten(pids, 2, `${c.what}: the build to start`)
        running.child.kill('SIGINT')
        r = await running.done
      } else {
        r = run(rig, ['--post-status'], { ...c.env, PIDS: pids })
      }
      assert.equal(r.code, c.code, `${c.what}: ${r.stdout}\n${r.stderr}`)
      for (const says of c.says) assert.match(`${r.stdout}\n${r.stderr}`, says, c.what)
      const [folder, ...more] = await readdir(rig.tmpBase)
      assert.ok(folder !== undefined && more.length === 0, `${c.what}: expected the one temp folder to be left, found ${[folder, ...more].join(', ')}`)
      const where = join(rig.tmpBase, folder)
      const leftLine = `left behind ${c.entries} entries (${c.entries} office-*) in the run's own temp folder, which could not be removed, so it is still at ${where}: EACCES`
      assert.ok(r.stdout.split('\n').some((line) => line.startsWith(leftLine)), `${c.what}: the report does not say the folder was left, and where:\n${r.stdout}`)
      const kept = (await report(rig))['tempFolderKept'] as { path: string; why: string } | null
      assert.equal(kept?.path, where, c.what)
      assert.match(kept?.why ?? '', /^EACCES/, c.what)
      assert.equal(existsSync(rig.lock), false, `${c.what}: the lock was kept because the folder could not be removed`)
    } finally {
      await unlock(rig)
    }
  }

  // A second signal releases what it can at once, and a folder it cannot remove does not keep the
  // lock from going with it. The typecheck's output is held, so the first signal alone would take
  // two seconds to end the run.
  const rig = await aRepo(t)
  const pids = pidFile(t)
  try {
    const running = start(t, rig, [], { STEP_LOCK_DIR: 'typecheck', STEP_HOLD: 'typecheck', PIDS: pids })
    const stderr = collect(running.child.stderr)
    await pidsWritten(pids, 1, 'the typecheck to leave its output held')
    running.child.kill('SIGINT')
    await until(() => (stderr().includes('SIGINT: stopping') ? true : undefined), 'the run to take the first SIGINT')
    running.child.kill('SIGINT')
    const r = await running.done
    assert.equal(r.code, 130, `${r.stdout}\n${r.stderr}`)
    assert.doesNotMatch(r.stdout, /^result /m, 'the second SIGINT did not end the run at once')
    const [folder] = await readdir(rig.tmpBase)
    assert.ok(r.stderr.includes(`could not remove the run's temp folder, so it is still at ${join(rig.tmpBase, folder ?? '')}: EACCES`), r.stderr)
    assert.equal(existsSync(rig.lock), false, 'the second SIGINT left the lock, because the folder could not be removed')
  } finally {
    await unlock(rig)
  }
})
